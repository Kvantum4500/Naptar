import 'time.dart';

/// Marker stored in the notes of generated shifts, so regenerating replaces
/// only these and never events the user typed in by hand.
const kShiftMarker = 'Beosztás-generátor';

/// One block of the repeating cycle: [days] consecutive days of the same kind.
/// [title] == null means days off.
class ShiftStep {
  const ShiftStep.off(this.days) : title = null, startMinutes = 0, minutes = 0;
  const ShiftStep.work(
    this.title,
    this.days, {
    required this.startMinutes,
    required this.minutes,
  });

  final String? title;
  final int days;

  /// Minutes after midnight (wall clock) at which the shift starts.
  final int startMinutes;

  /// Length of the shift in minutes (may run past midnight).
  final int minutes;

  bool get isOff => title == null;
}

class PlannedShift {
  const PlannedShift(this.title, this.start, this.end);
  final String title;

  /// Floating wall-clock start/end.
  final DateTime start;
  final DateTime end;
}

/// The user's usual cycle: 3 nights, 3 off, 3 days, 3 off.
const defaultShiftCycle = <ShiftStep>[
  ShiftStep.work('Éjszakai műszak', 3, startMinutes: 18 * 60, minutes: 12 * 60),
  ShiftStep.off(3),
  ShiftStep.work('Nappali műszak', 3, startMinutes: 6 * 60, minutes: 12 * 60),
  ShiftStep.off(3),
];

/// Expands [cycle] from [startDay] (floating date, first day of the first
/// step) up to but excluding [untilDay]. Pure wall-clock arithmetic: a shift
/// starts and ends at the stated clock times even across a DST change.
List<PlannedShift> generateShiftPlan(
  List<ShiftStep> cycle, {
  required DateTime startDay,
  required DateTime untilDay,
}) {
  final steps = cycle.where((s) => s.days > 0).toList();
  if (steps.isEmpty) return const [];
  final cycleDays = steps.fold<int>(0, (a, s) => a + s.days);
  final out = <PlannedShift>[];
  final first = floating(startDay.year, startDay.month, startDay.day);
  final end = floating(untilDay.year, untilDay.month, untilDay.day);
  for (var day = first, i = 0; day.isBefore(end); i++) {
    // Calendar-day stepping (UTC-flagged, so no DST drift).
    day = first.add(Duration(days: i));
    if (!day.isBefore(end)) break;
    var n = i % cycleDays;
    for (final s in steps) {
      if (n < s.days) {
        if (!s.isOff) {
          final st = day.add(Duration(minutes: s.startMinutes));
          out.add(
            PlannedShift(s.title!, st, st.add(Duration(minutes: s.minutes))),
          );
        }
        break;
      }
      n -= s.days;
    }
  }
  return out;
}

/// What a month looks like in terms of generated shifts.
class ShiftSummary {
  const ShiftSummary({
    required this.year,
    required this.month,
    required this.counts,
    required this.hours,
    required this.workDays,
    required this.offDays,
  });
  final int year;
  final int month;

  /// Shifts per title (e.g. "Éjszakai műszak": 6).
  final Map<String, int> counts;

  /// Total shift hours of shifts STARTING in the month.
  final double hours;

  /// Days of the month on which a shift starts / does not start.
  final int workDays;
  final int offDays;
}

/// Counts the shifts generated by the shift planner (notes == [kShiftMarker])
/// that START in the given month. A night shift belongs to the day it starts
/// on, so one running over midnight is never counted twice.
ShiftSummary summarizeShifts(
  Iterable<({String title, String notes, DateTime start, DateTime end})>
  events, {
  required int year,
  required int month,
}) {
  final counts = <String, int>{};
  final days = <int>{};
  var minutes = 0;
  for (final e in events) {
    if (e.notes != kShiftMarker) continue;
    if (e.start.year != year || e.start.month != month) continue;
    counts[e.title] = (counts[e.title] ?? 0) + 1;
    days.add(e.start.day);
    minutes += e.end.difference(e.start).inMinutes;
  }
  final total = DateTime.utc(year, month + 1, 0).day;
  return ShiftSummary(
    year: year,
    month: month,
    counts: counts,
    hours: minutes / 60,
    workDays: days.length,
    offDays: total - days.length,
  );
}
